// 轉換函數
function convertToTraditional(text) {
  let result = text;
  
  // 使用對照表進行轉換
  for (const [simplified, traditional] of Object.entries(conversionMap)) {
    const regex = new RegExp(simplified, 'g');
    result = result.replace(regex, traditional);
  }
  
  return result;
}

// 處理 JSON 檔案
function processJsonFile(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf8');
    const jsonData = JSON.parse(content);
    
    // 遞迴轉換所有字串值
    function convertObject(obj) {
      if (typeof obj === 'string') {
        return convertToTraditional(obj);
      } else if (Array.isArray(obj)) {
        return obj.map(convertObject);
      } else if (typeof obj === 'object' && obj !== null) {
        const result = {};
        for (const [key, value] of Object.entries(obj)) {
          result[key] = convertObject(value);
        }
        return result;
      }
      return obj;
    }
    
    const convertedData = convertObject(jsonData);
    
    // 生成繁體中文檔案路徑
    const zhTwPath = filePath.replace('zh-CN', 'zh-TW');
    
    // 確保目錄存在
    const dir = path.dirname(zhTwPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    
    // 寫入轉換後的檔案
    fs.writeFileSync(zhTwPath, JSON.stringify(convertedData, null, 2), 'utf8');
    
    console.log(`✅ 已轉換: ${filePath} -> ${zhTwPath}`);
    return true;
  } catch (error) {
    console.error(`❌ 轉換失敗: ${filePath}`, error.message);
    return false;
  }
}

// 處理 Markdown 檔案
function processMarkdownFile(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf8');
    const convertedContent = convertToTraditional(content);
    
    const zhTwPath = filePath.replace('zh-CN', 'zh-TW');
    const dir = path.dirname(zhTwPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    
    fs.writeFileSync(zhTwPath, convertedContent, 'utf8');
    console.log(`✅ 已轉換: ${filePath} -> ${zhTwPath}`);
    return true;
  } catch (error) {
    console.error(`❌ 轉換失敗: ${filePath}`, error.message);
    return false;
  }
}

// 主函數
function main() {
  console.log('🚀 開始 NocoBase 繁體中文化...\n');
  
  // 獲取所有簡體中文檔案
  const zhCnFiles = execSync('find . -name "*zh-CN*" -type f', { encoding: 'utf8' })
    .trim()
    .split('\n')
    .filter(file => file.length > 0);
  
  console.log(`📋 找到 ${zhCnFiles.length} 個簡體中文檔案\n`);
  
  let successCount = 0;
  let failCount = 0;
  
  zhCnFiles.forEach(filePath => {
    if (filePath.endsWith('.json')) {
      if (processJsonFile(filePath)) {
        successCount++;
      } else {
        failCount++;
      }
    } else if (filePath.endsWith('.md')) {
      if (processMarkdownFile(filePath)) {
        successCount++;
      } else {
        failCount++;
      }
    } else {
      console.log(`⏭️  跳過: ${filePath} (不支援的檔案類型)`);
    }
  });
  
  console.log(`\n🎉 轉換完成!`);
  console.log(`✅ 成功: ${successCount} 個檔案`);
  console.log(`❌ 失敗: ${failCount} 個檔案`);
  console.log(`📁 總計: ${zhCnFiles.length} 個檔案`);
}

// 執行
